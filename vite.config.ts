import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import basicSsl from '@vitejs/plugin-basic-ssl';
import type { Plugin } from 'vite';
import { defineConfig } from 'vitest/config';

/**
 * Writes dist/sw.js after the build: a small precaching service worker so the
 * booth keeps working when the venue's internet drops. The cache name is a hash
 * of the built files, so every deploy replaces the previous cache.
 */
function boothServiceWorker(): Plugin {
  let outDir = 'dist';
  return {
    name: 'booth-service-worker',
    apply: 'build',
    configResolved(config) {
      outDir = config.build.outDir;
    },
    closeBundle() {
      const files: string[] = [];
      const walk = (dir: string) => {
        for (const name of readdirSync(dir)) {
          // Hidden files (e.g. macOS .DS_Store) are often not served by web hosts,
          // and a single failed download would stop the whole cache from installing.
          if (name.startsWith('.')) continue;
          const full = join(dir, name);
          if (statSync(full).isDirectory()) walk(full);
          else files.push(full);
        }
      };
      walk(outDir);

      const hash = createHash('sha256');
      const assets = files
        .filter((f) => !f.endsWith(`${sep}sw.js`) && !f.endsWith('.map'))
        .sort()
        .map((f) => {
          hash.update(f).update(readFileSync(f));
          return `./${relative(outDir, f).split(sep).join('/')}`;
        });
      const version = hash.digest('hex').slice(0, 12);

      const source = `// Generated by vite.config.ts — do not edit.
const CACHE = 'booth-${version}';
const ASSETS = ${JSON.stringify(['./', ...assets])};

// A new version only downloads here. It takes over when the page says the booth
// is idle; the page then reloads, so it never asks for files of the old version.
self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(ASSETS)));
});

self.addEventListener('message', (event) => {
  if (event.data === 'activate-now') self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(keys.filter((k) => k.startsWith('booth-') && k !== CACHE).map((k) => caches.delete(k))),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  if (new URL(request.url).origin !== self.location.origin) return;
  if (request.mode === 'navigate') {
    event.respondWith(
      caches.match('./index.html', { cacheName: CACHE }).then((hit) => hit || fetch(request)),
    );
    return;
  }
  event.respondWith(
    caches.match(request, { cacheName: CACHE, ignoreSearch: true }).then((hit) => hit || fetch(request)),
  );
});
`;
      writeFileSync(join(outDir, 'sw.js'), source);
    },
  };
}

/** When this build was made, Jakarta time, shown in the booth's settings to tell versions apart. */
const BUILT_AT = new Date(Date.now() + 7 * 3_600_000).toISOString().slice(0, 16).replace('T', ' ');

export default defineConfig(({ mode }) => ({
  define: { __BUILT_AT__: JSON.stringify(BUILT_AT) },
  // Relative base so the build can be hosted at any path (root or sub-folder).
  base: './',
  // "lan" mode serves over HTTPS with a self-signed certificate, because iPad
  // Safari only grants camera access on secure origins.
  plugins: [mode === 'lan' ? basicSsl() : null, boothServiceWorker()],
  server: { port: 5173 },
  build: { target: 'es2022' },
  test: { environment: 'node', include: ['tests/**/*.test.ts'] },
}));
